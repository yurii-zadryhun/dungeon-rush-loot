"""A/B test the shared Universal greedy and opportunity policies on matched drops.

The generated stream is SYNTHETIC, not the game's actual loot distribution.
Never compare final scores generated by different objective versions.
"""
from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

from src.domain import ScoringStrategy
from src.equipment import EquipmentCodec
from src.scoring import BuildScorer
from src.strategies import strategy_for
from tools.simulate_strategy_loot import (
    DEFAULT_EQUIPMENT, random_item, run_strategy, universal_target_report,
)


def compare(seeds: tuple[int, ...] = (20261011, 12345, 81292),
            iterations: int = 5000) -> list[dict]:
    start = EquipmentCodec.loads_json(DEFAULT_EQUIPMENT.read_text(encoding="utf-8"))
    objective = BuildScorer(strategy_for(ScoringStrategy.UNIVERSAL))
    results = []
    for seed in seeds:
        generator = random.Random(seed)
        drops = tuple(random_item(generator) for _ in range(iterations))
        variants = {}
        for name, lookahead in (("greedy", False), ("opportunity", True)):
            state = run_strategy(
                drops, start, ScoringStrategy.UNIVERSAL, iterations,
                universal_lookahead=lookahead,
            )
            variants[name] = {
                "equips": state.equipped,
                "score": round(objective.score(state.final).total, 3),
                "goals": universal_target_report(state.final),
            }
        results.append({"seed": seed, **variants})
    return results


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--iterations", type=int, default=5000)
    parser.add_argument("--output", type=Path,
                        default=Path("dist/universal-opportunity-comparison.json"))
    args = parser.parse_args()
    result = compare(iterations=args.iterations)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
